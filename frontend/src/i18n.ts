export const DICTS: Record<Lang, Dict> = { en, zh, ms, ta };

/* ------------------------------------------------------------ language state */
const STORE = "prereads.lang";
export const LANG_EVENT = "prereads:lang";
const isLang = (v: unknown): v is Lang => v === "en" || v === "zh" || v === "ms" || v === "ta";

/** zh* -> zh, ms* -> ms, ta* -> ta, anything else -> en. */
export function langFrom(tag: string | undefined | null): Lang {
  const t = (tag || "").toLowerCase();
  if (t.startsWith("zh")) return "zh";
  if (t.startsWith("ms")) return "ms";
  if (t.startsWith("ta")) return "ta";
  return "en";
}

/** The saved choice, else the browser's language. */
export function getLang(): Lang {
  try {
    const saved = globalThis.localStorage?.getItem(STORE);
    if (isLang(saved)) return saved;
  } catch {
    /* storage blocked: fall through to the browser language */
  }
  return langFrom(typeof navigator === "undefined" ? "" : navigator.language);
}

let active: Lang | null = null;
const current = (): Lang => (active ??= getLang());
/** The language in use right now (no re-render; use useLang() in components). */
export const currentLang = current;

function applyHtmlLang(lang: Lang) {
  if (typeof document !== "undefined") document.documentElement.lang = LANGS.find((l) => l.id === lang)!.html;
}

export function setLang(lang: Lang) {
  active = lang;
  try {
    globalThis.localStorage?.setItem(STORE, lang);
  } catch {
    /* not saved, still applied for this visit */
  }
  applyHtmlLang(lang);
  if (typeof window !== "undefined") window.dispatchEvent(new CustomEvent(LANG_EVENT, { detail: lang }));
}

/** Re-renders the component whenever the language changes. */
export function useLang(): Lang {
  const [lang, set] = useState<Lang>(current);
  useEffect(() => {
    const on = () => set(current());
    window.addEventListener(LANG_EVENT, on);
    on();
    return () => window.removeEventListener(LANG_EVENT, on);
  }, []);
  return lang;
}

/** BCP-47 code for the browser voice (en-SG, zh-CN, ms-MY, ta-IN). */
export const voiceLang = (lang: Lang = current()) => LANGS.find((l) => l.id === lang)!.voice;

/* ------------------------------------------------------------ translate */
type Vars = Record<string, string | number>;

function fill(s: string, vars?: Vars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Translated string with {name} interpolation; falls back to English, then to the key. */
export function t(key: Key, vars?: Vars, lang: Lang = current()): string {
  return fill(DICTS[lang][key] ?? en[key] ?? key, vars);
}

type PluralBase = Key extends infer K ? (K extends `${infer B}.one` ? B : never) : never;

/** Plural pick: `${base}.one` when n is 1, else `${base}.other`. {n} is filled in. */
export function tn(base: PluralBase, n: number, vars?: Vars, lang: Lang = current()): string {
  return t(`${base}.${n === 1 ? "one" : "other"}` as Key, { n, ...vars }, lang);
}

/** Like t(), but {name} can be a React node (a <strong>, a <select>, a <code>). */
export function rich(key: Key, vars: Record<string, ReactNode>, lang: Lang = current()): ReactNode {
  const s = DICTS[lang][key] ?? en[key] ?? key;
  const parts = s.split(/\{(\w+)\}/g).map((p, i) => (i % 2 === 1 ? (p in vars ? vars[p] : `{${p}}`) : p));
  return createElement(Fragment, null, ...parts);
}

/** rich() with the plural pick of tn(). */
export function richN(base: PluralBase, n: number, vars: Record<string, ReactNode>, lang: Lang = current()): ReactNode {
  return rich(`${base}.${n === 1 ? "one" : "other"}` as Key, { n, ...vars }, lang);
}

